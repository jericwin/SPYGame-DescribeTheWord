// 15. Event Listeners Initialization
function initEventListeners() {
  // Players stepper
  dom.btnDecPlayers.addEventListener("click", () => {
    if (gameState.totalPlayers > 3) {
      gameState.totalPlayers--;
      updateStepperDisplays();
      soundFx.playClick();
    }
  });

  dom.btnIncPlayers.addEventListener("click", () => {
    if (gameState.totalPlayers < 20) {
      gameState.totalPlayers++;
      updateStepperDisplays();
      soundFx.playClick();
    }
  });

  // Spies stepper
  dom.btnDecSpies.addEventListener("click", () => {
    if (gameState.totalSpies > 1) {
      gameState.totalSpies--;
      updateStepperDisplays();
      soundFx.playClick();
    }
  });

  dom.btnIncSpies.addEventListener("click", () => {
    const maxSpies = Math.max(1, Math.floor((gameState.totalPlayers - 1) / 2));
    if (gameState.totalSpies < maxSpies) {
      gameState.totalSpies++;
      updateStepperDisplays();
      soundFx.playClick();
    }
  });

  // Language buttons
  dom.langBtnEn.addEventListener("click", () => {
    soundFx.playClick();
    setLanguage("en");
  });

  dom.langBtnFil.addEventListener("click", () => {
    soundFx.playClick();
    setLanguage("fil");
  });

  // Difficulty buttons
  dom.diffButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      soundFx.playClick();
      const diff = btn.dataset.diff;
      setDifficulty(diff);
    });
  });

  // Timer chips
  dom.timerChips.forEach(chip => {
    chip.addEventListener("click", () => {
      soundFx.playClick();
      dom.timerChips.forEach(c => c.classList.remove("active"));
      chip.classList.add("active");

      const val = chip.dataset.minutes;
      if (val === "custom") {
        gameState.selectedTimerMinutes = "custom";
        dom.customTimerBox.classList.remove("hidden");
        dom.timerBadge.textContent = "Custom Duration";
      } else {
        gameState.selectedTimerMinutes = parseInt(val, 10);
        dom.customTimerBox.classList.add("hidden");
        dom.timerBadge.textContent = `${val} Minutes`;
      }
    });
  });

  dom.customTimerInput.addEventListener("input", (e) => {
    const v = parseInt(e.target.value, 10);
    if (!isNaN(v) && v > 0) {
      dom.timerBadge.textContent = `${v} Minutes`;
    }
  });

  // Select all / Deselect all categories
  dom.btnSelectAllCats.addEventListener("click", () => {
    soundFx.playClick();
    gameState.selectedCategories = Object.keys(localizedDatabases[gameState.language]);
    dom.configErrorMsg.classList.add("hidden");
    renderCategoryCards();
  });

  dom.btnClearCats.addEventListener("click", () => {
    soundFx.playClick();
    gameState.selectedCategories = [];
    renderCategoryCards();
  });

  // Start game from config
  dom.btnPlayGame.addEventListener("click", startGame);

  // Privacy confirm button
  dom.btnConfirmIdentity.addEventListener("click", () => {
    soundFx.playClick();
    setupSecretCardForCurrentPlayer();
  });

  // 3D Card Tap to Reveal / Hide
  dom.secretCardElement.addEventListener("click", toggleSecretCard);
  dom.secretCardElement.addEventListener("keydown", (e) => {
    if (e.key === "Enter" || e.key === " ") {
      e.preventDefault();
      toggleSecretCard();
    }
  });

  // Next player pass
  dom.btnNextPlayerPass.addEventListener("click", handlePassToNextPlayer);

  // Ready screen -> Start discussion
  dom.btnStartDiscussion.addEventListener("click", startDiscussion);

  // Discussion timer controls
  dom.btnPauseResume.addEventListener("click", togglePauseResumeTimer);
  dom.btnGoVoting.addEventListener("click", goToVoting);

  // Modal controls
  dom.btnModalCancel.addEventListener("click", () => {
    soundFx.playClick();
    closeModal();
  });
  dom.btnModalConfirm.addEventListener("click", confirmElimination);

  // Reveal screen continue
  dom.btnContinueGame.addEventListener("click", handleContinueAfterReveal);

  // Game over buttons
  dom.btnPlayAgain.addEventListener("click", playAgain);
  dom.btnNewGame.addEventListener("click", newGame);
}

