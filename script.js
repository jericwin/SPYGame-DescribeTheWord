/**
 * Picks 2 completely distinct, real words filtered by the chosen difficulty level:
 * - Easy: Top 33% most common words
 * - Medium: Middle 34% standard words
 * - Hard: Upper 33% uncommon words
 * - Random: Full pool
 */
function selectRandomWord() {
  const currentDb = localizedDatabases[gameState.language];
  const randomCatKey = gameState.selectedCategories[Math.floor(Math.random() * gameState.selectedCategories.length)];
  const catObj = currentDb[randomCatKey];

  gameState.selectedCategory = randomCatKey;
  gameState.selectedCategoryTitle = catObj.title;

  const fullPool = catObj.words;
  const n = fullPool.length;
  const third = Math.floor(n / 3);

  let activeTier = gameState.difficulty;
  if (activeTier === "random") {
    // Pick a tier dynamically for this round
    const tiers = ["easy", "medium", "hard"];
    activeTier = tiers[Math.floor(Math.random() * tiers.length)];
    gameState.wordTier = `RANDOM (${activeTier.toUpperCase()})`;
  } else {
    gameState.wordTier = activeTier.toUpperCase();
  }

  // Filter pool according to difficulty
  let pool;
  if (activeTier === "easy") {
    pool = fullPool.slice(0, third);
  } else if (activeTier === "medium") {
    pool = fullPool.slice(third, third * 2);
  } else if (activeTier === "hard") {
    pool = fullPool.slice(third * 2);
  } else {
    pool = fullPool;
  }

  if (!pool || pool.length < 10) pool = fullPool;

  // Pick Civilian Word
  const civIndex = Math.floor(Math.random() * pool.length);
  gameState.civilianWord = pool[civIndex];

  // Pick Spy Word: Must be completely distinct (different index and string)
  let spyIndex = Math.floor(Math.random() * pool.length);
  let attempts = 0;
  while ((pool[spyIndex] === gameState.civilianWord || Math.abs(spyIndex - civIndex) < 4) && attempts < 50) {
    spyIndex = Math.floor(Math.random() * pool.length);
    attempts++;
  }
  gameState.spyWord = pool[spyIndex];
}

function generatePlayers() {
  gameState.players = [];
  for (let i = 1; i <= gameState.totalPlayers; i++) {
    gameState.players.push({
      id: i,
      name: `Player ${i}`,
      role: "Civilian",
      word: gameState.civilianWord,
      eliminated: false
    });
  }
}

function assignRoles() {
  const indices = [];
  for (let i = 0; i < gameState.totalPlayers; i++) indices.push(i);

  // Shuffle indices
  for (let i = indices.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [indices[i], indices[j]] = [indices[j], indices[i]];
  }

  // Assign Spies
  for (let s = 0; s < gameState.totalSpies; s++) {
    const spyIdx = indices[s];
    gameState.players[spyIdx].role = "Spy";
    gameState.players[spyIdx].word = gameState.spyWord;
  }
}

function startGame() {
  if (!validateConfiguration()) {
    soundFx.playAlert();
    return;
  }

  soundFx.playClick();
  selectRandomWord();
  generatePlayers();
  assignRoles();

  gameState.currentPlayerIndex = 0;
  gameState.currentRound = 1;
  gameState.cardRevealed = false;
  gameState.cardEverRevealedByCurrentPlayer = false;

  showPlayerTurn();
}

